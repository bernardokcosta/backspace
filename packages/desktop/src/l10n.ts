export const DESKTOP_CATALOGS: Record<DesktopLanguage, Catalog> = {
  en, ru, de, pt, zh,
  es, fr, it, ro, tr, uk, pl, nl, sv, da, nb,
  fi, cs, ar, hi, id, vi, th, ja, ko,
};

export function isDesktopLanguage(value: unknown): value is DesktopLanguage {
  return typeof value === 'string' && (DESKTOP_LANGUAGES as readonly string[]).includes(value);
}

export function isDesktopLanguagePreference(value: unknown): value is DesktopLanguagePreference {
  return value === 'auto' || isDesktopLanguage(value);
}

/** `de-AT` → `de`; anything not shipped → null. Same rule as the web client. */
function baseLanguage(tag: string): DesktopLanguage | null {
  const part = tag.trim().toLowerCase().split('-')[0] ?? '';
  const base = part === 'no' ? 'nb' : part;
  return isDesktopLanguage(base) ? base : null;
}

/**
 * Stored explicit choice first, then the ordered OS UI languages, then English.
 */
export function resolveDesktopLanguage(
  stored: string | null,
  systemLanguages: readonly string[],
  released: ReadonlySet<string> = releasedLanguages,
): DesktopLanguage {
  if (isDesktopLanguage(stored) && released.has(stored)) return stored;
  for (const tag of systemLanguages) {
    const language = baseLanguage(tag);
    if (language && released.has(language)) return language;
  }
  return 'en';
}

export function translateDesktop(
  language: DesktopLanguage,
  key: DesktopStringKey,
  values?: Record<string, string>,
): string {
  const text = DESKTOP_CATALOGS[language][key] || en[key];
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => values[name] ?? match);
}

// ---------------------------------------------------------------------------
// Persistence: one JSON file next to instance-url.json.
// ---------------------------------------------------------------------------

export function getLanguagePath(): string {
  return path.join(app.getPath('userData'), 'language.json');
}

export function loadStoredLanguage(): DesktopLanguagePreference | null {
  try {
    const data = JSON.parse(fs.readFileSync(getLanguagePath(), 'utf-8')) as { language?: unknown };
    return isDesktopLanguagePreference(data.language) ? data.language : null;
  } catch {
    return null;
  }
}

let livePreference: DesktopLanguagePreference | undefined;

export function saveStoredLanguage(language: DesktopLanguagePreference): void {
  livePreference = language;
  fs.writeFileSync(getLanguagePath(), JSON.stringify({ language }));
}

export function getDesktopLanguagePreference(): DesktopLanguagePreference {
  livePreference ??= loadStoredLanguage() ?? 'auto';
  return livePreference;
}

export function getSystemLanguages(): readonly string[] {
  try {
    return app.getPreferredSystemLanguages();
  } catch {
    return [];
  }
}

/** Cached preference, freshly resolved OS languages; disk failure cannot freeze auto. */
export function getDesktopLanguage(): DesktopLanguage {
  return resolveDesktopLanguage(getDesktopLanguagePreference(), getSystemLanguages());
}

export function getDesktopLanguageQuery(): { lang: DesktopLanguage; preference: DesktopLanguagePreference; released: string } {
  return { lang: getDesktopLanguage(), preference: getDesktopLanguagePreference(), released: RELEASED_DESKTOP_LANGUAGES.join(',') };
}
